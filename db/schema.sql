-- Bhakti Sagar – MySQL / MariaDB schema
-- Usage:  mysql -u root < db/schema.sql
-- (db/seed.php also runs this file automatically)

CREATE DATABASE IF NOT EXISTS `bhakti_sagar`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `bhakti_sagar`;

CREATE TABLE IF NOT EXISTS `tracks` (
  `id`            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `slug`          VARCHAR(80)  NOT NULL,
  `title_hi`      VARCHAR(190) NOT NULL,
  `title_en`      VARCHAR(190) NOT NULL,
  `title_gu`      VARCHAR(190) NOT NULL DEFAULT '',
  `type`          ENUM('shloka','bhajan','aarti') NOT NULL DEFAULT 'bhajan',
  `deity`         VARCHAR(90)  NOT NULL DEFAULT '',
  `singer`        VARCHAR(120) NOT NULL DEFAULT '',
  `youtube_id`    VARCHAR(20)  DEFAULT NULL,
  `slots`         VARCHAR(120) NOT NULL DEFAULT '',
  `tags`          VARCHAR(190) NOT NULL DEFAULT '',
  `blurb`         VARCHAR(255) NOT NULL DEFAULT '',
  `is_active`     TINYINT(1)   NOT NULL DEFAULT 1,
  `sort_order`    SMALLINT     NOT NULL DEFAULT 0,
  `created_at`    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_tracks_slug` (`slug`),
  KEY `idx_tracks_type` (`type`),
  KEY `idx_tracks_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `daily_shlokas` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `key`         VARCHAR(60)  NOT NULL,
  `sanskrit`    TEXT         NOT NULL,
  `translit`    VARCHAR(500) NOT NULL DEFAULT '',
  `source`      VARCHAR(190) NOT NULL DEFAULT '',
  `meaning_hi`  VARCHAR(500) NOT NULL DEFAULT '',
  `is_active`   TINYINT(1)   NOT NULL DEFAULT 1,
  `created_at`  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_shloka_key` (`key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Permanent panchang dataset, generated by tools/generate-panchang.mjs
-- from @ishubhamx/panchangam-js (MIT, Drik Ganita) into data/panchang.json
-- and imported here by db/seed.php.
CREATE TABLE IF NOT EXISTS `panchang_days` (
  `d`             DATE         NOT NULL COMMENT 'civil day (Asia/Kolkata)',
  `var_num`       TINYINT UNSIGNED NOT NULL COMMENT '0=Sunday',
  `var_key`       VARCHAR(8)   NOT NULL COMMENT 'sun..sat',
  `var_hi`        VARCHAR(20)  NOT NULL,
  `tithi`         TINYINT UNSIGNED NOT NULL COMMENT '1..30, udaya tithi',
  `tithi_hi`      VARCHAR(20)  NOT NULL,
  `paksha`        VARCHAR(8)   NOT NULL COMMENT 'shukla|krishna',
  `paksha_hi`     VARCHAR(16)  NOT NULL,
  `nakshatra`     TINYINT UNSIGNED NOT NULL COMMENT '0..26',
  `nakshatra_hi`  VARCHAR(30)  NOT NULL,
  `sunrise`       VARCHAR(5)   NOT NULL COMMENT 'HH:MM IST',
  `sunset`        VARCHAR(5)   NOT NULL COMMENT 'HH:MM IST',
  `festivals`     VARCHAR(1000) NOT NULL DEFAULT '' COMMENT 'comma separated festival slugs',
  `updated_at`    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`d`),
  KEY `idx_panchang_var` (`var_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- वार / तिथि / त्योहार → track suggestion rules (source: data/day_rules.php)
CREATE TABLE IF NOT EXISTS `day_rules` (
  `id`           INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `rule_type`    ENUM('var','tithi','festival') NOT NULL,
  `match_val`    VARCHAR(60)  NOT NULL COMMENT 'var key | tithi group | festival slug substring',
  `priority`     TINYINT      NOT NULL DEFAULT 1 COMMENT 'festival=3, tithi=2, var=1',
  `badge_hi`     VARCHAR(120) NOT NULL,
  `note_hi`      VARCHAR(255) NOT NULL DEFAULT '',
  `track_slugs`  VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'comma separated track slugs',
  `is_active`    TINYINT(1)   NOT NULL DEFAULT 1,
  `created_at`   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_day_rule` (`rule_type`, `match_val`),
  KEY `idx_day_rules_type` (`rule_type`, `is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
