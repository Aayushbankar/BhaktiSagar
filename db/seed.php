<?php
declare(strict_types=1);

/*
 * Seeds MySQL with the devotional catalogue (YouTube links, slots, shlokas).
 *
 * CLI:    php db/seed.php
 * Web:    http://localhost/bhakti-sagar/db/seed.php   (only allowed from localhost)
 *
 * Safe to run repeatedly – it upserts rows by slug/key.
 */

$root = dirname(__DIR__);
$config = require $root . '/config.php';
$catalog = require $root . '/data/catalog.php';

$isCli = PHP_SAPI === 'cli';
if (!$isCli) {
    $remote = $_SERVER['REMOTE_ADDR'] ?? '';
    if (!in_array($remote, ['127.0.0.1', '::1'], true)) {
        http_response_code(403);
        exit('Forbidden - run from CLI or localhost.');
    }
    header('Content-Type: text/plain; charset=utf-8');
}

function out(string $line): void
{
    echo $line . PHP_EOL;
}

function fail(string $message): void
{
    out('ERROR: ' . $message);
    exit(1);
}

$db = $config['db'];

try {
    $server = new PDO(
        sprintf('mysql:host=%s;port=%d;charset=%s', $db['host'], $db['port'], $db['charset']),
        $db['user'],
        $db['pass'],
        [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_TIMEOUT => 5,
        ]
    );
} catch (Throwable $e) {
    fail('Cannot connect to MySQL on ' . $db['host'] . ':' . $db['port'] . ' - ' . $e->getMessage());
}

out('Connected to MySQL ' . $server->getAttribute(PDO::ATTR_SERVER_VERSION));

// 1. schema
$sql = file_get_contents($root . '/db/schema.sql');
if ($sql === false) {
    fail('Cannot read db/schema.sql');
}
foreach (array_filter(array_map('trim', explode(';', $sql))) as $statement) {
    $server->exec($statement);
}
out('Schema ready (database `' . $db['name'] . '`).');

$pdo = new PDO(
    sprintf('mysql:host=%s;port=%d;dbname=%s;charset=%s', $db['host'], $db['port'], $db['name'], $db['charset']),
    $db['user'],
    $db['pass'],
    [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]
);

// upgrade pre-existing installs: Gujarati titles (added 2026-10)
$hasTitleGu = $pdo->query("SHOW COLUMNS FROM `tracks` LIKE 'title_gu'")->fetch();
if (!$hasTitleGu) {
    $pdo->exec("ALTER TABLE `tracks` ADD COLUMN `title_gu` VARCHAR(190) NOT NULL DEFAULT '' AFTER `title_en`");
    out('tracks.title_gu column added.');
}

// 2. tracks
$insertTrack = $pdo->prepare(
    'INSERT INTO tracks (slug, title_hi, title_en, title_gu, type, deity, singer, youtube_id, slots, tags, blurb, sort_order)
     VALUES (:slug, :title_hi, :title_en, :title_gu, :type, :deity, :singer, :youtube_id, :slots, :tags, :blurb, :sort_order)
     ON DUPLICATE KEY UPDATE
        title_hi = VALUES(title_hi), title_en = VALUES(title_en), title_gu = VALUES(title_gu), type = VALUES(type),
        deity = VALUES(deity), singer = VALUES(singer), youtube_id = VALUES(youtube_id),
        slots = VALUES(slots), tags = VALUES(tags), blurb = VALUES(blurb),
        sort_order = VALUES(sort_order), is_active = 1, updated_at = CURRENT_TIMESTAMP'
);

$trackCount = 0;
foreach ($catalog['tracks'] as $track) {
    $insertTrack->execute([
        ':slug' => $track['slug'],
        ':title_hi' => $track['title_hi'],
        ':title_en' => $track['title_en'],
        ':title_gu' => $track['title_gu'] ?? '',
        ':type' => $track['type'],
        ':deity' => $track['deity'],
        ':singer' => $track['singer'],
        ':youtube_id' => $track['youtube_id'] ?? null,
        ':slots' => $track['slots'],
        ':tags' => $track['tags'],
        ':blurb' => $track['blurb'],
        ':sort_order' => $track['sort_order'] ?? 0,
    ]);
    $trackCount++;
}
out('Tracks upserted: ' . $trackCount);

$keepSlugs = array_column($catalog['tracks'], 'slug');
if ($keepSlugs) {
    $ph = implode(',', array_fill(0, count($keepSlugs), '?'));
    $stale = $pdo->prepare("DELETE FROM tracks WHERE slug NOT IN ($ph)");
    $stale->execute($keepSlugs);
    if ($stale->rowCount() > 0) {
        out('Stale tracks removed: ' . $stale->rowCount());
    }
}

// 3. daily shlokas
$insertShloka = $pdo->prepare(
    'INSERT INTO daily_shlokas (`key`, sanskrit, translit, source, meaning_hi)
     VALUES (:key, :sanskrit, :translit, :source, :meaning_hi)
     ON DUPLICATE KEY UPDATE
        sanskrit = VALUES(sanskrit), translit = VALUES(translit),
        source = VALUES(source), meaning_hi = VALUES(meaning_hi), is_active = 1'
);

$shlokaCount = 0;
foreach ($catalog['daily_shlokas'] as $shloka) {
    $insertShloka->execute([
        ':key' => $shloka['key'],
        ':sanskrit' => $shloka['sanskrit'],
        ':translit' => $shloka['translit'],
        ':source' => $shloka['source'],
        ':meaning_hi' => $shloka['meaning_hi'],
    ]);
    $shlokaCount++;
}
out('Daily shlokas upserted: ' . $shlokaCount);

// 4. permanent panchang dataset (generated by tools/generate-panchang.mjs)
$panchangFile = $root . '/data/panchang.json';
if (!is_file($panchangFile)) {
    out('SKIP: data/panchang.json not found (run: cd tools && npm install && node generate-panchang.mjs).');
} else {
    $raw = file_get_contents($panchangFile);
    $panchang = json_decode((string) $raw, true);
    if (!is_array($panchang) || !isset($panchang['days'])) {
        fail('data/panchang.json is not valid JSON.');
    }

    $varaKey = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
    $varaHi = ['रविवार', 'सोमवार', 'मंगलवार', 'बुधवार', 'गुरुवार', 'शुक्रवार', 'शनिवार'];
    $tithiHi = [
        'प्रतिपदा', 'द्वितीया', 'तृतीया', 'चतुर्थी', 'पंचमी', 'षष्ठी', 'सप्तमी', 'अष्टमी', 'नवमी', 'दशमी',
        'एकादशी', 'द्वादशी', 'त्रयोदशी', 'चतुर्दशी', 'पूर्णिमा', 'प्रतिपदा', 'द्वितीया', 'तृतीया', 'चतुर्थी', 'पंचमी',
        'षष्ठी', 'सप्तमी', 'अष्टमी', 'नवमी', 'दशमी', 'एकादशी', 'द्वादशी', 'त्रयोदशी', 'चतुर्दशी', 'अमावस्या',
    ];
    $nakshatraHi = [
        'अश्विनी', 'भरणी', 'कृत्तिका', 'रोहिणी', 'मृगशिरा', 'आर्द्रा', 'पुनर्वसु', 'पुष्य', 'आश्लेषा', 'मघा',
        'पूर्वाफाल्गुनी', 'उत्तराफाल्गुनी', 'हस्त', 'चित्रा', 'स्वाति', 'विशाखा', 'अनुराधा', 'ज्येष्ठा', 'मूल',
        'पूर्वाषाढ़ा', 'उत्तराषाढ़ा', 'श्रवण', 'धनिष्ठा', 'शतभिषा', 'पूर्वाभाद्रपदा', 'उत्तराभाद्रपदा', 'रेवती',
    ];

    $insertDay = $pdo->prepare(
        'INSERT INTO panchang_days
            (d, var_num, var_key, var_hi, tithi, tithi_hi, paksha, paksha_hi,
             nakshatra, nakshatra_hi, sunrise, sunset, festivals)
         VALUES
            (:d, :var_num, :var_key, :var_hi, :tithi, :tithi_hi, :paksha, :paksha_hi,
             :nakshatra, :nakshatra_hi, :sunrise, :sunset, :festivals)
         ON DUPLICATE KEY UPDATE
            var_num = VALUES(var_num), var_key = VALUES(var_key), var_hi = VALUES(var_hi),
            tithi = VALUES(tithi), tithi_hi = VALUES(tithi_hi), paksha = VALUES(paksha),
            paksha_hi = VALUES(paksha_hi), nakshatra = VALUES(nakshatra),
            nakshatra_hi = VALUES(nakshatra_hi), sunrise = VALUES(sunrise),
            sunset = VALUES(sunset), festivals = VALUES(festivals)'
    );

    $panchangCount = 0;
    $festCount = 0;
    foreach ($panchang['days'] as $dateKey => $day) {
        $varNum = (int) $day['var'];
        $tithiNum = (int) $day['tithi'];
        $nakNum = (int) $day['nakshatra'];
        $paksha = $day['paksha'] === 'krishna' ? 'krishna' : 'shukla';
        $insertDay->execute([
            ':d' => $dateKey,
            ':var_num' => $varNum,
            ':var_key' => $varaKey[$varNum],
            ':var_hi' => $varaHi[$varNum],
            ':tithi' => $tithiNum,
            ':tithi_hi' => $tithiHi[$tithiNum - 1],
            ':paksha' => $paksha,
            ':paksha_hi' => $paksha === 'krishna' ? 'कृष्ण पक्ष' : 'शुक्ल पक्ष',
            ':nakshatra' => $nakNum,
            ':nakshatra_hi' => $nakshatraHi[$nakNum],
            ':sunrise' => (string) $day['sunrise'],
            ':sunset' => (string) $day['sunset'],
            ':festivals' => implode(',', $day['festivals'] ?? []),
        ]);
        $panchangCount++;
        $festCount += count($day['festivals'] ?? []);
    }
    $meta = $panchang['meta'] ?? [];
    out('Panchang days upserted: ' . $panchangCount .
        ' (' . ($meta['range'][0] ?? '?') . ' → ' . ($meta['range'][1] ?? '?') .
        ', engine: ' . ($meta['engine'] ?? 'unknown') . ', festivals: ' . $festCount . ')');
}

// 5. panchang day rules (वार / तिथि / त्योहार)
$dayRules = require $root . '/data/day_rules.php';
$insertRule = $pdo->prepare(
    'INSERT INTO day_rules (rule_type, match_val, priority, badge_hi, note_hi, track_slugs)
     VALUES (:rule_type, :match_val, :priority, :badge_hi, :note_hi, :track_slugs)
     ON DUPLICATE KEY UPDATE
        priority = VALUES(priority), badge_hi = VALUES(badge_hi),
        note_hi = VALUES(note_hi), track_slugs = VALUES(track_slugs), is_active = 1'
);
$ruleCount = 0;
foreach ($dayRules['rules'] as $rule) {
    $insertRule->execute([
        ':rule_type' => $rule['type'],
        ':match_val' => $rule['match'],
        ':priority' => $rule['priority'],
        ':badge_hi' => $rule['badge_hi'],
        ':note_hi' => $rule['note_hi'],
        ':track_slugs' => implode(',', $rule['tracks']),
    ]);
    $ruleCount++;
}
out('Day rules upserted: ' . $ruleCount);

$keepRules = array_map(static fn(array $r): string => $r['type'] . ':' . $r['match'], $dayRules['rules']);
if ($keepRules) {
    $ph = implode(',', array_fill(0, count($keepRules), '?'));
    $staleRule = $pdo->prepare("DELETE FROM day_rules WHERE CONCAT(rule_type, ':', match_val) NOT IN ($ph)");
    $staleRule->execute($keepRules);
    if ($staleRule->rowCount() > 0) {
        out('Stale day rules removed: ' . $staleRule->rowCount());
    }
}

$totals = $pdo->query(
    'SELECT (SELECT COUNT(*) FROM tracks) AS tracks,
            (SELECT COUNT(*) FROM daily_shlokas) AS shlokas,
            (SELECT COUNT(*) FROM panchang_days) AS panchang,
            (SELECT COUNT(*) FROM day_rules) AS rules'
)->fetch();
out('Database totals: tracks=' . $totals['tracks'] . ', shlokas=' . $totals['shlokas'] .
    ', panchang_days=' . $totals['panchang'] . ', day_rules=' . $totals['rules']);
out('Done. Open the site – api/ will now serve data from MySQL.');
